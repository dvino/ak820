#!/usr/bin/env python3
"""Exercise the production updater with files and a fake HID device only.

The ROMs are deliberately synthetic test fixtures. Their expected hashes are
injected into the reference checks; no physical USB access or firmware write
is possible through this harness.
"""
import contextlib
import io
import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'util'))
import ak820_tool as updater
import pack_ak820 as packer
from startup_fixture import add_startup_fixture
from oem_fixture import make_synthetic_oem, patch_synthetic_oem


def reply(command):
    result = bytearray(65)
    result[:9] = bytes((0, command, 0xaa, 0x55, 0, 0xfa, 0xfa, 0xfa, 0xfa))
    if command == 1:
        result[9:13] = bytes.fromhex('00112233')
    return bytes(result)


class FakeHID:
    def __init__(self):
        self.descriptors = [dict(path=b'fake-loader', interface_number=1, usage_page=12, usage=1)]
        self.enumerations = []
        self.opened = []
        self.sent = []
        self.closed = False
        self.responses = {}
        self.short_write_at = None

    def enumerate(self, vid, pid):
        self.enumerations.append((vid, pid))
        if (vid, pid) != (0x0c45, 0x7687):
            raise AssertionError('Unexpected device family')
        return self.descriptors

    def device(self):
        return self

    def open_path(self, path):
        self.opened.append(path)

    def close(self):
        self.closed = True

    def send_feature_report(self, packet):
        assert len(packet) == 65 and packet[0] == 0
        self.sent.append(bytes(packet))
        return 64 if len(self.sent) == self.short_write_at else 65

    def get_feature_report(self, report_id, size):
        assert report_id == 0 and size == 65
        command = self.sent[-1][1]
        return self.responses.get(command, reply(command))


class FlashGuardsTest(unittest.TestCase):
    def setUp(self):
        self.stack = contextlib.ExitStack()
        self.addCleanup(self.stack.close)
        self.root = Path(self.stack.enter_context(tempfile.TemporaryDirectory(prefix='ak820-flash-test-')))
        self.session = self.root / 'session'
        self.session.mkdir()
        (self.root / 'reference').mkdir()
        # Generated bytes let the production immutable-span gates run without
        # carrying any vendor ROM in the checkout.
        self.stock, self.native, _, _ = make_synthetic_oem()
        self.backup = self.stock
        self.stack.enter_context(patch.object(updater, 'ROOT', self.root))
        patch_synthetic_oem(self.stack, updater, self.stock)
        (self.root / 'reference/stock-full.bin').write_bytes(self.stock)
        (self.root / 'reference/native-installed.bin').write_bytes(self.native)
        symbols = {name: packer.CODE_START + 3 + i for i, name in enumerate((
            '__sdcc_gsinit_startup', '_USB_DeviceInterrupt', '_ak820_timer_irq',
            '_ak820_led_irq', '_keymaps', '_encoder_map'))}
        data = dict(enumerate(packer.ljmp(symbols['__sdcc_gsinit_startup']), packer.CODE_START))
        data.update({address: 0x22 for address in symbols.values()})
        add_startup_fixture(data, symbols)
        self.payloads = {name: packer.pack(data, symbols, self.stock,
                         bytes(packer.empty_nvm()), trial)
                         for name, trial in (('trial', True), ('permanent', False))}
        self.payloads['restore'] = self.native
        self.manifest = {'backup_sha256': packer.digest(self.backup), 'images': {}}
        for name, payload in self.payloads.items():
            filename = updater.IMAGES[name]
            (self.session / filename).write_bytes(payload)
            self.manifest['images'][filename] = {'sha256': packer.digest(payload), 'size': len(payload)}
        (self.session / 'before-full-rom.bin').write_bytes(self.backup)
        self.save_manifest()
        self.hid = FakeHID()
        self.hid_mock = self.stack.enter_context(patch.object(updater, 'hid_module', return_value=self.hid))
        self.stack.enter_context(patch.object(updater.time, 'sleep'))
        self.stack.enter_context(contextlib.redirect_stdout(io.StringIO()))

    def save_manifest(self):
        (self.session / 'images.json').write_text(json.dumps(self.manifest))

    def flash(self, name='trial', enter_loader=False, accept=False):
        updater.flash(self.session, name, enter_loader, accept)

    def assert_no_usb(self):
        self.hid_mock.assert_not_called()
        self.assertEqual(self.hid.sent, [])

    def test_plan_never_imports_or_opens_hid(self):
        result = updater.plan(self.session, 'trial')
        self.assertFalse(result['usb_opened'])
        self.assertFalse(result['device_write_performed'])
        self.assertEqual(result['data_blocks'], 799)
        self.assert_no_usb()

    def test_damaged_backup_stops_before_usb(self):
        (self.session / 'before-full-rom.bin').write_bytes(self.backup[:-1])
        with self.assertRaisesRegex(ValueError, 'recovery backup'):
            self.flash()
        self.assert_no_usb()

    def test_rehashed_unknown_loader_stops_before_usb(self):
        backup = bytearray(self.backup)
        backup[0x100] ^= 1
        (self.session / 'before-full-rom.bin').write_bytes(backup)
        self.manifest['backup_sha256'] = packer.digest(backup)
        self.save_manifest()
        with self.assertRaisesRegex(ValueError, 'protected tail|OEM loader'):
            self.flash()
        self.assert_no_usb()

    def test_rehashed_unknown_native_code_stops_before_usb(self):
        backup = bytearray(self.backup)
        backup[0x5000] ^= 1
        recovery = backup[packer.APP_START:packer.APP_END]
        (self.session / 'before-full-rom.bin').write_bytes(backup)
        (self.session / updater.IMAGES['restore']).write_bytes(recovery)
        self.manifest['backup_sha256'] = packer.digest(backup)
        self.manifest['images'][updater.IMAGES['restore']]['sha256'] = packer.digest(recovery)
        self.save_manifest()
        with self.assertRaisesRegex(ValueError, 'Unsupported native application'):
            self.flash()
        self.assert_no_usb()

    def test_rehashed_recovery_must_equal_backup(self):
        recovery = bytearray(self.native)
        recovery[-1] ^= 1
        (self.session / updater.IMAGES['restore']).write_bytes(recovery)
        self.manifest['images'][updater.IMAGES['restore']]['sha256'] = packer.digest(recovery)
        self.save_manifest()
        with self.assertRaisesRegex(ValueError, 'Recovery image'):
            self.flash()
        self.assert_no_usb()

    def test_rehashed_payload_still_requires_internal_checksum(self):
        payload = bytearray(self.payloads['trial'])
        payload[0x100] ^= 1
        (self.session / updater.IMAGES['trial']).write_bytes(payload)
        self.manifest['images'][updater.IMAGES['trial']]['sha256'] = packer.digest(payload)
        self.save_manifest()
        with self.assertRaisesRegex(ValueError, 'Application checksum'):
            self.flash()
        self.assert_no_usb()

    def test_permanent_needs_both_verified_trial_and_explicit_acceptance(self):
        for prepared, accepted in ((False, False), (False, True), (True, False)):
            with self.subTest(prepared=prepared, accepted=accepted):
                if prepared:
                    self.manifest['permanent_prepared_from_verified_trial'] = 'fixture'
                else:
                    self.manifest.pop('permanent_prepared_from_verified_trial', None)
                self.save_manifest()
                with self.assertRaisesRegex(ValueError, 'physical operation'):
                    self.flash('permanent', accept=accepted)
                self.assert_no_usb()

    def test_multiple_loaders_never_open_or_erase(self):
        self.hid.descriptors *= 2
        with self.assertRaisesRegex(RuntimeError, 'Multiple loader'):
            self.flash()
        self.assertEqual(self.hid.opened, [])
        self.assertEqual(self.hid.sent, [])

    def test_invalid_identity_status_framing_or_length_never_erases(self):
        malformed = []
        for position in (0, 1, 3, 5, 9):
            item = bytearray(reply(1))
            item[position] ^= 1
            malformed.append(bytes(item))
        malformed.extend((reply(1)[:-1], b''))
        for response in malformed:
            with self.subTest(response=response.hex()):
                self.hid.sent.clear()
                self.hid.closed = False
                self.hid.responses[1] = response
                with self.assertRaises(ValueError):
                    self.flash()
                self.assertEqual(self.hid.sent, [b'\0' + updater.loader_packet(1)])
                self.assertTrue(self.hid.closed)

    def test_short_identity_write_never_erases(self):
        self.hid.short_write_at = 1
        with self.assertRaisesRegex(OSError, 'Incomplete loader'):
            self.flash()
        self.assertEqual(self.hid.sent, [b'\0' + updater.loader_packet(1)])
        self.assertTrue(self.hid.closed)

    def test_failed_erase_ack_stops_before_programming(self):
        self.hid.responses[2] = b''
        with self.assertRaises(ValueError):
            self.flash()
        self.assertEqual([packet[1] for packet in self.hid.sent], [1, 2])
        self.assertTrue(self.hid.closed)

    def test_stale_live_backup_never_requests_loader_or_erase(self):
        class ChangedApplication:
            entered = False
            closed = False

            def rom(inner, address, size):
                self.assertEqual((address, size), (0, 65536))
                return self.backup[:-1] + bytes((self.backup[-1] ^ 1,))

            def enter_native_loader(inner):
                inner.entered = True

            def close(inner):
                inner.closed = True

        app = ChangedApplication()
        self.hid.descriptors = []
        with patch.object(updater, 'Application', return_value=app):
            with self.assertRaisesRegex(RuntimeError, 'Live ROM differs'):
                self.flash(enter_loader=True)
        self.assertFalse(app.entered)
        self.assertTrue(app.closed)
        self.assertEqual(self.hid.opened, [])
        self.assertEqual(self.hid.sent, [])

    def test_successful_mock_transfer_has_exact_range_blocks_and_checksum(self):
        self.flash()
        payload = self.payloads['trial']
        expected = [updater.loader_packet(1), updater.loader_packet(2),
                    updater.loader_packet(3, packer.APP_START, len(payload) // 64)]
        expected += [payload[offset:offset + 64] for offset in range(0, len(payload), 64)]
        expected += [updater.loader_packet(4, 0, sum(payload) & 0xffffffff), updater.loader_packet(5)]
        self.assertEqual(self.hid.sent, [b'\0' + item for item in expected])
        self.assertTrue(self.hid.closed)
        self.assertEqual((self.session / 'before-full-rom.bin').read_bytes(), self.backup)
        self.assertEqual((self.session / updater.IMAGES['restore']).read_bytes(), self.native)


if __name__ == '__main__':
    unittest.main()
